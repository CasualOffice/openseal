// Scratch: open the editor's fields step and evaluate an expression (argv[2]) in the page.
import { chromium } from "@playwright/test";
import { MOCK } from "../mock.js";
import { makePdf } from "../mockpdf.js";
const BASE = "http://127.0.0.1:8391";
const [w, hgt] = (process.argv[3] || "1440x900").split("x").map(Number);
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: w, height: hgt } });
page.on("pageerror", (e) => console.log("PAGEERROR", String(e)));
await page.goto(`${BASE}/app.html?mock=1#/signin`);
await page.getByLabel("Email").fill(MOCK.email);
await page.getByLabel("Password").fill(MOCK.password);
await page.getByRole("button", { name: "Sign in" }).click();
await page.getByRole("heading", { name: "Home", exact: true }).waitFor();
await page.goto(`${BASE}/app.html?mock=1#/prepare`);
await page.getByTestId("pdf-input").setInputFiles({ name: "c.pdf", mimeType: "application/pdf", buffer: Buffer.from(makePdf([1, 2, 3].map((n) => ({ title: `P${n}`, lines: ["x"] })))) });
await page.getByTestId("wizard-next").click();
await page.getByRole("button", { name: /Add recipient/ }).first().click();
await page.getByTestId("wizard-next").click();
await page.waitForTimeout(800);
console.log(JSON.stringify(await page.evaluate(process.argv[2]), null, 1));
await b.close();
