"""Generate src/tables.rs: standard-14 widths, base encodings and a glyph-name subset.

The numbers are public facts (Adobe's AFM files for the standard 14 fonts, the base
encodings of ISO 32000-2 Annex D and the Adobe Glyph List). They are read here from
reportlab (BSD) and pypdf (BSD-3), installed in a throwaway venv:

    ~/.local/bin/uv venv target/pyvenv
    VIRTUAL_ENV=target/pyvenv ~/.local/bin/uv pip install pypdf reportlab
    target/pyvenv/bin/python -I crates/casual-sign-fields/tools/gen_tables.py \
        > crates/casual-sign-fields/src/tables.rs

Only data is taken; no code is copied.
"""
import re
import sys

from pypdf._codecs.adobe_glyphs import adobe_glyphs
from reportlab.pdfbase import _fontdata

FONTS = ["Helvetica", "Helvetica-Bold", "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"]


def wanted(cp):
    return cp < 0x0530 or 0x1E00 <= cp < 0x1F00 or 0x2000 <= cp < 0x2200 or 0xFB00 <= cp <= 0xFB06


def main():
    names = {}
    for k, v in adobe_glyphs.items():
        n = k[1:]
        if len(v) != 1 or not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", n):
            continue
        if re.fullmatch(r"uni[0-9A-F]{4}|u[0-9A-F]{4,6}", n):
            continue
        cp = ord(v)
        if wanted(cp):
            names[n] = cp

    out = sys.stdout
    out.write("//! Generated by `tools/gen_tables.py`; do not edit. Public facts: Adobe AFM widths of\n")
    out.write("//! the standard 14 fonts, the base encodings of ISO 32000-2 Annex D, and a subset of\n")
    out.write("//! the Adobe Glyph List.\n\n")

    def enc_table(name, rust):
        glyphs = _fontdata.encodings[name]
        out.write(f"/// `{name}`: code to Unicode scalar, 0 where undefined.\n")
        out.write(f"pub(crate) static {rust}: [u16; 256] = [\n")
        row = []
        for code in range(256):
            g = glyphs[code]
            cp = 0
            if g and ("/" + g) in adobe_glyphs and len(adobe_glyphs["/" + g]) == 1:
                cp = ord(adobe_glyphs["/" + g])
            row.append(str(cp))
        for i in range(0, 256, 16):
            out.write("    " + ", ".join(row[i:i + 16]) + ",\n")
        out.write("];\n\n")

    enc_table("WinAnsiEncoding", "WIN_ANSI")
    enc_table("MacRomanEncoding", "MAC_ROMAN")
    enc_table("StandardEncoding", "STANDARD")

    win = _fontdata.encodings["WinAnsiEncoding"]
    for f in FONTS:
        rust = f.upper().replace("-", "_")
        w = _fontdata.widthsByFontGlyph[f]
        vals = []
        for code in range(32, 256):
            g = win[code]
            vals.append(str(int(round(w.get(g, 0)))) if g else "0")
        out.write(f"/// `{f}` widths (1/1000 em) for WinAnsiEncoding codes 32 to 255; 0 where undefined.\n")
        out.write(f"pub(crate) static {rust}: [u16; 224] = [\n")
        for i in range(0, 224, 16):
            out.write("    " + ", ".join(vals[i:i + 16]) + ",\n")
        out.write("];\n\n")
    rows = [(f, a, d) for f, (a, d) in sorted(_fontdata.ascent_descent.items()) if f not in ("Symbol", "ZapfDingbats")]
    out.write("/// Ascender and descender (1/1000 em) of the standard 14 text fonts.\n")
    out.write(f"pub(crate) static ASCENT_DESCENT: [(&str, i16, i16); {len(rows)}] = [\n")
    for f, a, d in rows:
        out.write(f"    (\"{f}\", {a}, {d}),\n")
    out.write("];\n\n")
    out.write("/// Glyph names to Unicode, sorted by name, for `/Differences` (Adobe Glyph List subset).\n")
    out.write(f"pub(crate) static GLYPH_NAMES: [(&str, u16); {len(names)}] = [\n")
    for n in sorted(names):
        out.write(f"    (\"{n}\", {names[n]}),\n")
    out.write("];\n")


main()
