#!/usr/bin/env python3
"""Generate the TypeScript and Python SDKs' operation tables from api/openapi.yaml, the
API contract (slice 8, `VS-08E`, docs/40 §7):

    python3 tools/build-sdks.py           # write the generated files
    python3 tools/build-sdks.py --check   # fail, naming the file, if one is stale

Generated, and never edited by hand:

- sdk/typescript/operations.js — every public operation (all of `/api/v1` and
  `/.well-known`; the signing ceremony's `/s/` and the embedded views' own `/e/` are not
  public API, docs/40 §5, §6): its HTTP
  method, path, path parameters, query parameters and whether it takes a JSON body.
- sdk/typescript/operations.d.ts — the client's typed method for each operation.
- sdk/python/openseal/_operations.py — the same table for the Python client.

The clients themselves (sdk/typescript/index.js, sdk/python/openseal/client.py) are
written by hand and read only these tables, so a new operation in the contract is a new
method once this runs. Needs PyYAML (as tools/build-api-docs.py does); fails non-zero
and says so without it.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "api/openapi.yaml"
TS_JS = ROOT / "sdk/typescript/operations.js"
TS_DTS = ROOT / "sdk/typescript/operations.d.ts"
PY = ROOT / "sdk/python/openseal/_operations.py"
METHODS = ("get", "post", "put", "patch", "delete")
HEADER = "Generated by tools/build-sdks.py from api/openapi.yaml. Do not edit."


def operations(spec: dict) -> list[dict]:
    """The public operations, sorted by operationId."""
    out = []
    for path, item in spec["paths"].items():
        if path.startswith("/s/") or path.startswith("/e/"):
            continue
        shared = item.get("parameters", [])
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            params = [resolve(spec, p) for p in shared + op.get("parameters", [])]
            content = (op.get("requestBody") or {}).get("content", {})
            out.append({
                "id": op["operationId"],
                "method": method.upper(),
                "path": path,
                "path_params": re.findall(r"\{([^}]+)\}", path),
                "query": sorted({p["name"] for p in params if p.get("in") == "query"}),
                "body": "application/json" in content,
                "body_required": bool((op.get("requestBody") or {}).get("required")) and "application/json" in content,
                "summary": " ".join(str(op.get("summary", "")).split()),
                "scope": op.get("x-permission", ""),
            })
    ids = [o["id"] for o in out]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"build-sdks: operationId used twice: {dupes}")
    return sorted(out, key=lambda o: o["id"])


def resolve(spec: dict, p: dict) -> dict:
    ref = p.get("$ref")
    if not ref:
        return p
    node = spec
    for part in ref.lstrip("#/").split("/"):
        node = node[part]
    return node


def table(ops: list[dict]) -> dict:
    return {o["id"]: {k: o[k] for k in ("method", "path", "path_params", "query", "body", "body_required")} for o in ops}


def ts_js(ops: list[dict]) -> str:
    body = json.dumps(table(ops), indent=2, sort_keys=True)
    return (f"// {HEADER}\n// Every public operation of the OpenSeal API (docs/40): method, path, path and query\n"
            f"// parameters, and whether it takes a JSON body. index.js builds a method from each.\n"
            f"export const OPERATIONS = Object.freeze({body});\n")


def ts_dts(ops: list[dict]) -> str:
    lines = [f"// {HEADER}", "", "/** The parameters of one call: path and query parameters by name, and `body` for a JSON body. */",
             "export type Params = Record<string, unknown> & { body?: unknown };", "",
             "/** One method per operation of the OpenSeal API (docs/40). */", "export interface Operations {"]
    for o in ops:
        named = o["path_params"] + o["query"]
        fields = [f"{json.dumps(n)}{'' if n in o['path_params'] else '?'}: string | number | boolean" for n in named]
        if o["body"]:
            fields.append(f"body{'' if o['body_required'] else '?'}: unknown")
        need = bool(o["path_params"]) or o["body_required"]
        arg = f"params{'' if need else '?'}: {{ {'; '.join(fields)} }}" if fields else "params?: Record<string, never>"
        lines.append(f"  /** {o['summary'] or o['id']} — `{o['method']} {o['path']}`{' (' + o['scope'] + ')' if o['scope'] not in ('', 'public') else ''} */")
        lines.append(f"  {o['id']}({arg}): Promise<any>;")
    lines.append("}")
    lines.append("")
    lines.append("export declare const OPERATIONS: Readonly<Record<keyof Operations, { method: string; path: string; path_params: string[]; query: string[]; body: boolean; body_required: boolean }>>;")
    return "\n".join(lines) + "\n"


def py(ops: list[dict]) -> str:
    body = json.dumps(table(ops), indent=4, sort_keys=True).replace("true", "True").replace("false", "False")
    return (f'"""{HEADER}\n\nEvery public operation of the OpenSeal API (docs/40): method, path, path and query\n'
            f'parameters, and whether it takes a JSON body. client.py builds a method from each.\n"""\n\n'
            f"OPERATIONS = {body}\n")


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        import yaml
    except ImportError:
        raise SystemExit("build-sdks: needs PyYAML to read api/openapi.yaml (pip install pyyaml)")
    ops = operations(yaml.safe_load(SPEC.read_text(encoding="utf8")))
    stale = []
    for path, text in ((TS_JS, ts_js(ops)), (TS_DTS, ts_dts(ops)), (PY, py(ops))):
        if check:
            if not path.exists() or path.read_text(encoding="utf8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf8")
    if stale:
        print("build-sdks: stale, run python3 tools/build-sdks.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"build-sdks: {len(ops)} operations{' checked' if check else ' written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
